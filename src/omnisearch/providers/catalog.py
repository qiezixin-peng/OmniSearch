from omnisearch.domain.enums import AdapterReliability, Channel, SourceCategory, SourceRole
from omnisearch.domain.models import ProviderCapabilities, SourceDefinition
from omnisearch.providers.registry import SourceRegistry


def _adapter(
    source_id: str,
    adapter_id: str,
    category: SourceCategory,
    channel: Channel,
    *,
    backend: str,
    capabilities: set[str],
    credentials: bool = False,
    date_filter: bool = False,
    domain_filter: bool = False,
    pagination: bool = True,
    concurrency: int = 2,
    reliability: AdapterReliability | None = None,
) -> ProviderCapabilities:
    return ProviderCapabilities(
        source_id=source_id,
        adapter_id=adapter_id,
        category=category,
        channel=channel,
        supported_languages={"*"},
        search_capabilities=capabilities,
        supports_pagination=pagination,
        supports_date_filter=date_filter,
        supports_domain_filter=domain_filter,
        max_concurrency=concurrency,
        requires_credentials=credentials,
        backend=backend,
        reliability_class=(
            reliability
            or (
                AdapterReliability.BROWSER_BEST_EFFORT
                if channel is Channel.BROWSER
                else (
                    AdapterReliability.CREDENTIALED_API
                    if credentials
                    else AdapterReliability.PUBLIC_API
                )
            )
        ),
    )


def _source(
    source_id: str,
    display_name: str,
    category: SourceCategory,
    role: SourceRole,
    priority: int,
    *adapters: ProviderCapabilities,
    enabled_by_default: bool = True,
) -> SourceDefinition:
    return SourceDefinition(
        source_id=source_id,
        display_name=display_name,
        category=category,
        role=role,
        priority=priority,
        enabled_by_default=enabled_by_default,
        adapters=list(adapters),
    )


